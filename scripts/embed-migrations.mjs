/**
 * Copies the Drizzle SQL migrations (drizzle/*.sql) into src/lib/db/migrations.ts so the server can
 * create/upgrade tables without reading files at runtime (Hostinger runs the app from its own folder).
 * Runs automatically after `npm run db:generate`.
 */
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const journal = JSON.parse(fs.readFileSync(path.join(root, "drizzle", "meta", "_journal.json"), "utf8"));
const entries = journal.entries.map((e) => {
  const sql = fs.readFileSync(path.join(root, "drizzle", `${e.tag}.sql`), "utf8");
  const statements = sql
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean);
  return { tag: e.tag, statements };
});

const out = `// GENERATED by scripts/embed-migrations.mjs from drizzle/*.sql — do not edit by hand.
export const MIGRATIONS: { tag: string; statements: string[] }[] = ${JSON.stringify(entries, null, 2)};
`;
fs.writeFileSync(path.join(root, "src", "lib", "db", "migrations.ts"), out);
console.log(`Embedded ${entries.length} migration(s) into src/lib/db/migrations.ts`);
